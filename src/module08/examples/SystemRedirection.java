package module08.examples;

import java.io.ByteArrayInputStream;
import java.io.ByteArrayOutputStream;
import java.io.InputStream;
import java.io.PrintStream;
import java.nio.charset.StandardCharsets;
import java.util.Scanner;

/**
 * Demonstrates techniques for intercepting and redirecting standard I/O streams
 * ({@code System.out}, {@code System.err}, and {@code System.in}) for automated testing.
 *
 * <p>Key concepts covered:
 * <ul>
 *   <li>Redirecting {@code System.out} to a {@link ByteArrayOutputStream} to assert console output.</li>
 *   <li>Redirecting {@code System.in} using {@link ByteArrayInputStream} to simulate user keystrokes.</li>
 *   <li>Capturing diagnostic output from {@code System.err}.</li>
 *   <li>Guaranteed stream restoration using {@code try-finally} and an {@link AutoCloseable} harness.</li>
 *   <li>Preventing stream pollution across concurrent unit test suites.</li>
 * </ul>
 *
 * @author Java Mastery Curriculum
 * @version 21.0
 */
public class SystemRedirection {

    public static void main(String[] args) {
        System.out.println("==================================================");
        System.out.println("   MODULE 08: SYSTEM I/O STREAM REDIRECTION       ");
        System.out.println("==================================================\n");

        demonstrateOutputRedirection();
        demonstrateInputRedirection();
        demonstrateSafeAutoCloseableHarness();
    }

    /**
     * Demonstrates capturing console output generated by arbitrary business logic
     * by redirecting {@code System.out}.
     */
    public static void demonstrateOutputRedirection() {
        System.out.println("--- 1. Capturing System.out for Unit Testing ---");

        // 1. Preserve original standard output stream
        PrintStream originalOut = System.out;
        ByteArrayOutputStream capturedBytes = new ByteArrayOutputStream();

        try {
            // 2. Redirect System.out to in-memory buffer
            System.setOut(new PrintStream(capturedBytes, true, StandardCharsets.UTF_8));

            // 3. Execute legacy or production code that prints to System.out
            executeBusinessReport();

        } finally {
            // 4. ALWAYS restore original System.out in a finally block!
            System.setOut(originalOut);
        }

        // 5. Inspect captured output
        String capturedText = capturedBytes.toString(StandardCharsets.UTF_8);
        System.out.println("Successfully captured output from redirected stream:");
        System.out.println(">>> START CAPTURE >>>");
        System.out.print(capturedText);
        System.out.println("<<< END CAPTURE <<<");

        boolean containsExpected = capturedText.contains("STATUS: SUCCESS");
        System.out.println("Assertion (capturedText contains 'STATUS: SUCCESS'): " + containsExpected);
        System.out.println();
    }

    /**
     * Demonstrates simulating interactive console input by redirecting {@code System.in}.
     */
    public static void demonstrateInputRedirection() {
        System.out.println("--- 2. Simulating User Typing by Redirecting System.in ---");

        InputStream originalIn = System.in;
        String simulatedUserInput = "42\nProduction Server\n";
        ByteArrayInputStream mockInput = new ByteArrayInputStream(simulatedUserInput.getBytes(StandardCharsets.UTF_8));

        try {
            // Redirect stdin to in-memory stream
            System.setIn(mockInput);

            // Execute code that expects console input from user
            Scanner scanner = new Scanner(System.in);
            int serverPort = Integer.parseInt(scanner.nextLine().trim());
            String serverName = scanner.nextLine().trim();

            System.out.println("Successfully read simulated port : " + serverPort);
            System.out.println("Successfully read simulated name : " + serverName);

        } finally {
            // Restore original System.in
            System.setIn(originalIn);
        }
        System.out.println();
    }

    /**
     * Production business logic method printing directly to {@code System.out}.
     */
    private static void executeBusinessReport() {
        System.out.println("[REPORT GENERATOR] Initiating system audit...");
        System.out.println("[REPORT GENERATOR] Audit completed. 0 vulnerabilities found.");
        System.out.println("[REPORT GENERATOR] STATUS: SUCCESS");
    }

    /**
     * Demonstrates an elegant {@link AutoCloseable} test fixture pattern that encapsulates
     * stream redirection cleanly in a {@code try-with-resources} block.
     */
    public static void demonstrateSafeAutoCloseableHarness() {
        System.out.println("--- 3. Industrial AutoCloseable I/O Capture Harness ---");

        try (OutputCapture capture = new OutputCapture()) {
            System.out.println("Message generated inside isolated test context!");
            System.err.println("Diagnostic warning captured simultaneously!");

            String stdOutput = capture.getStdout();
            String errOutput = capture.getStderr();

            // Notice that while inside this block, nothing printed to actual terminal
            // Now we verify the captured contents
            assert stdOutput.contains("Message generated");
            assert errOutput.contains("Diagnostic warning");
        }

        // Back to normal terminal here:
        System.out.println("System.out and System.err were automatically and safely restored.");
        System.out.println();
    }

    /**
     * Test utility class managing redirected stdout and stderr.
     */
    public static class OutputCapture implements AutoCloseable {
        private final PrintStream originalOut = System.out;
        private final PrintStream originalErr = System.err;
        private final ByteArrayOutputStream outBuffer = new ByteArrayOutputStream();
        private final ByteArrayOutputStream errBuffer = new ByteArrayOutputStream();

        public OutputCapture() {
            System.setOut(new PrintStream(outBuffer, true, StandardCharsets.UTF_8));
            System.setErr(new PrintStream(errBuffer, true, StandardCharsets.UTF_8));
        }

        public String getStdout() {
            return outBuffer.toString(StandardCharsets.UTF_8);
        }

        public String getStderr() {
            return errBuffer.toString(StandardCharsets.UTF_8);
        }

        @Override
        public void close() {
            System.setOut(originalOut);
            System.setErr(originalErr);
        }
    }
}
